# ╔═╡ 227727ac-c882-4c5e-8210-809df6885107
md""" 
Так как начальное распределение температуры, равно как и функции, задающие граничные условия первого рода, не зависят от теплопроводности, граничные и начальные условия для функций влияния будут нулевыми. 

Окончательно задача запишется в виде:

`` \frac{\partial J_i}{\partial t}  = a\frac{\partial^2 J_i}{\partial x^2} +
V(x,t) \frac{\partial J_i}{\partial x} + G(x,t)J_i + F_i``  

А функции ``T_x`` и ``T_{xx}`` получаются путем решения исходного уравнения.

"""

# ╔═╡ cd86bf3d-9cae-49c0-82d5-0bac54cf8a22
md"""
С нулевыми граничными условями первого рода:

``J_i|_{x=0,x=b} = 0, t \in [0,t_m]``

И нулевыми начальными условиями:

``J_i(x,0) =0 , x   \in [0,b]``
"""

# ╔═╡ 6d70e14e-13d4-487e-a8aa-0cf06d9a31c5
md"""
где, коэффициент диффузии:

``V = 2a\frac{\lambda'}{\lambda}T_x``
"""

# ╔═╡ 625dacfe-2e92-42e0-be24-9f05a011b1a5
md"""
Коэффициент перед первой производной по координате

``G(x,t) = T_{xx} [\frac {\lambda'C - C'\lambda}{C^2}] + \frac{\lambda'}{\lambda} T_x^2 [\frac {\lambda'C - C'\lambda}{C^2}] + aT_x^2 [\frac {\lambda''\lambda - (\lambda')^2}{\lambda ^2}]``

"""

# ╔═╡ c2121bf7-fd4e-422f-b314-794108a7f2dd
md"""
Последний член - функция источников:

``F_i =  \frac{\beta_i}{C}T_{xx}  + \frac{\beta_i}{C}\frac{\lambda'}{\lambda} T_x^2  + aT_x^2\frac{[\partial_{b_i}\lambda'] \lambda  - \lambda'\beta_i}{\lambda^2} ``

"""

# ╔═╡ 7004e3c5-fba2-4433-90e8-fd2a2cc3d897
md"""
Можно заметить несколько аспектов, которые позволяют упростить вычисления:

1) Коэффициенты ``G`` и ``V`` не зависят от ``\beta_i``, следовательно, если у нас есть решение исходного ДУ (то есть известны ``T,T_t,T_x T_{xx}``) эти коэффициенты будут одинаковыми для всех дифференциальных уравнений

2) Если коэффициент теплопроводности не зависит от температуры, то ``\beta_1=1``, все коэффициенты , содержащие производную теплопроводности по температуре станут равными нулю, останется только первый член ``F_i``  и часть коэффициента ``G``, мы получим уравнение для чувствительности:

`` \frac{\partial J_i}{\partial t}  = a\frac{\partial^2 J_i}{\partial x^2} - aT_{xx} [\frac { C'}{C}] J_i +
\frac{1}{C}T_{xx}`` 

