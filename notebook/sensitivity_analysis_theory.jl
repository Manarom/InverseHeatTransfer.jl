### Непрерывный подход

Тут получается, что так как параметры оптимизации входят в коэффициенты уравнения, то есть, от них зависит сам дифференциальный оператор, то , следовательно, и решение этого уравнения будет зависеть от этих параметров.

Обозначим производную по параметру оптимизации ``b_i`` как :

``J_i = \frac {d T}{d b_i}``

Очень важный для понимая момент состоит в том, что производая в данном случае должна учитывать полную вариацию решения при изменении параметров оптимизации, неокторые из членов уравнения зависят от параметров оптимизации в явном виде, но некоторые зависят опосредованно, через собственно решение задачи. 

Поэтому важно, что здесь стоит именно полная производная!

Задача состоит в том, чтобы продифференцировать исходное уравнение и поучить М новых уравнений для ``J_i``. Для этого продифференцируем исходное уравнение по ``b_i``:

``\frac {d}{d b_i} \frac{\partial T}{\partial t}  = \frac {d }{d b_i}[a(T)\frac{\partial^2 T}{\partial x^2}] +  \frac {d }{d b_i} [ a(T) \frac{\lambda'(T)}{\lambda(T)} (\frac{\partial T}{\partial x})^2]``

