Некоторая модель ``\vec{f}(t;\vec{a})``, которая должна описывать наблюдаемые ``\vec{y(t)}`` имеет набор параметров ``\vec{a}``, также известно, что для нахождения ``\vec{f}(t;\vec{a})`` необходимо решить уравнение вида:

