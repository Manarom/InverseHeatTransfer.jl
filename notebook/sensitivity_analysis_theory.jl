``\nabla_a\Phi(\vec{a}) = [\nabla_a \vec{f}] \cdot \vec{r}``

В квадратных скобках стоит матрица Якоби, которую обозначают иногда 

``J =[\nabla_a \vec{f}] = \frac{d}{d\vec{a}}\vec{f}``

Элементы этой матрицы соотвествуют ``i``-й координаты вектора ``\vec{f}`` по ``j``-й переменной оптимизации:

``J_{ij} = \frac {\partial f_j}{\partial a_i}``

