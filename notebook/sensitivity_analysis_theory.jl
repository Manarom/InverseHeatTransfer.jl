#### Постановка параметрической обратной задачи 

Наша задача - найти температурную зависимость теплопроводности по набору зависимостей температуры от времени, измеренным в ``k`` точках по толщине образца

``[\vec{y}|_{x_1}],...,\vec{y}|_{x_k}]``

Основая идея параметрической оптимизации, состоит в том, чтобы сделать предположения о форме температрной зависимости от времени, сохранив несколько параметров неопределенными, и, далее, подобрать эти параметры при помощи того или иного метода оптимизации. 

Для определенности предположим, что темпеатурная зависимость теплопроводности описывается полиномом некоторого произвольного базиса:

``\lambda(T) = \sum_{i=1}^{M}b_i\beta_i(T)``

где ``b_i`` - постоянные коэффициенты, не зависящие от температуры, а ``\beta_i(T)`` - базисные функции (мономиалы), например, для стандартного базиса ``\beta_i(T) = T^{i-1}``

Так как в уравнение входит не только сама теплопроводность, но и ее производная по температуре, то, так как коэффициенты производной полнома можно выразить через коэффициенты исходного полинома, то оставим пока их в таком виде

``\lambda'(T) = \sum_{i=1}^{M}b'_i(\vec{b})\beta_i(T)``

Конкретная форма зависимости ``b'_i(\vec{b})`` будет определяться типом полинома. 


